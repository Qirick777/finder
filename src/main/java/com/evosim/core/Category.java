package com.evosim.core;

/**
 * 특성 카테고리 (설계서 §2).
 * 개체는 카테고리별로 최대 3개의 발현 특성을 가진다 → 기본 12개(보조 신설 이후).
 */
public enum Category {
    DISPOSITION, // 성향 — 대립쌍(반발)
    PHYSICAL,    // 신체 — 대립쌍(반발)
    PREFERENCE,  // 선호 — 반발 없는 독립 가점(익숙함/다양성 축만 예외)
    /**
     * 보조 — <b>단독으로는 거의 무의미하고, 다른 특성·자산과 맞물릴 때만 발동</b>하는 축.
     * 메인 다이얼(수확량·착공비·지대·관리용량)을 직접 건드리지 않고 조건부로만 작동해,
     * 평균은 그대로 두고 <b>조합이 갖춰진 소수의 분산만</b> 넓힌다. 전부 대립쌍(반발)이라
     * 유전·무효화(반발 카드)가 다른 카테고리와 동일하게 성립한다.
     */
    AUXILIARY
}

package com.evosim.core;

/**
 * 특성 태그 (설계서 §2 "태그 — 특성과 발현을 분리").
 *
 * <p>우성은 "전달 확률"만 지배하고, 성별발현은 "발동 여부"만 지배한다 — 서로 간섭하지 않는다.
 * 흔적(발동 X)도 100% 유전되므로 숨은 변이 / 성적 대립 유전이 구현된다.
 */
public enum Tag {
    /** 우성: 자식에게 75% 확률로 우성으로 유전 (설계서 §2). */
    DOMINANT,
    /** 남성발현: 남성일 때만 발동. 여성이 가지면 흔적(발동 X, 유전은 됨). */
    MALE_EXPRESSED,
    /** 여성발현: 여성일 때만 발동. 남성이 가지면 흔적. */
    FEMALE_EXPRESSED
    // (남성발현+여성발현 동시 = 상쇄 → 항상 발동. 발현 판정은 Phase 1에서.)
}

package com.evosim.mod.entity;

/**
 * <b>시설의 수치</b> — 학교·교회의 문턱과 값. 한 곳에 모아 둔다.
 *
 * <p>전부 <b>측정 뒤에 확정할 값</b>이다. 판정 지표는 시설 수지(흑자여야 한다)와 시설 수
 * (0 도 난립도 아니어야 한다)이며, 0 이 나오면 사건 로그의 "보류/자리 없음" 줄이 <b>왜</b>
 * 0 인지 말해야 한다.
 */
public final class Facilities {

    private Facilities() {
    }

    /**
     * 학교 건축비 — 저장고에서 즉시 빠진다(인부를 산 값).
     *
     * <p>60 은 저택({@code MANSION.buildCost} 70) 바로 아래다. 학교는 1,336칸으로 저택
     * (1,027칸 중 비공기)보다 크지만, 저택은 <b>사는 집</b>이라 그 값 자체가 과시의 상한 노릇을
     * 한다. 학교를 그보다 비싸게 두면 저택을 지을 수 있는 자만 학교를 지을 수 있어 두 문턱이
     * 겹쳐 버린다 — 서로 다른 선택지가 되게 조금 아래에 둔다.
     */
    public static final double SCHOOL_COST = 60.0;

    /**
     * 학교를 세울 자격 — 거느린 자가 이만큼 있어야 한다.
     *
     * <p>계획서 1.5: "이용자가 많을수록 이익이므로 세력이 클수록 남는 장사이고, 작은 세력은
     * 적자라 시설을 못 짓는다." 그 문장을 그대로 수로 옮긴 것이 이 상수다. 6 은 실측(P4 D19)
     * 에서 주인 3명의 세력이 28·25·3 이었던 분포를 보고 잡았다 — 상위 둘만 자격이 되고
     * 말단 지주는 안 되는 자리다. <b>신분으로 분기하지 않는다</b>: 누구든 여섯을 거느리면 된다.
     */
    public static final int SCHOOL_MIN_FOLLOWERS = 6;

    /** 부지 탐색 — 세운 자의 집에서 이 거리부터 이 거리까지 고리를 넓히며 찾는다. */
    public static final int MIN_RADIUS = 12;
    public static final int SEARCH_RADIUS = 64;

    /** 거처와의 여유 — 시설 반경 + 이웃 거처 반경에 이만큼 더 띄운다(사람이 지나갈 길). */
    public static final int HOME_MARGIN = 4;

    /** 부지 지형 낙차 상한 — 이보다 울퉁불퉁하면 메움·파냄이 지형을 헤집는다. */
    public static final int MAX_SPREAD = 4;

    // ── 학교 운영(P5b) ─────────────────────────────────────────────────────
    /**
     * 하루 수업료 — 학생 가구 저장고에서 학교 주인에게.
     *
     * <p>"소액"(계획서 1.5)이다. 세금({@link com.evosim.core.Tribute#TAX_PER_FOLLOWER_DAY} 1.0)의
     * 절반이라, 아이를 학교에 보내는 것이 세금 한 번 더 내는 것보다는 가볍다. 못 내면 빚이
     * 되고 그 빚이 예속을 깊게 한다 — <b>시설은 예속의 도구다.</b>
     */
    public static final double TUITION_PER_DAY = 0.5;

    /**
     * 교사 하루 급여 — 학교 주인이 교사 가구에 낸다.
     *
     * <p>1.0 이면 학생 <b>셋</b>부터 흑자다(0.5×3 = 1.5 > 1.0). 계획서 1.5 의 "이용자가 많을수록
     * 이익이므로 세력이 클수록 남는 장사이고, 작은 세력은 적자라 시설을 못 짓는다"가
     * 이 두 수의 비로 성립한다. 착공 문턱이 추종자 6명인 것과 눈금이 맞는다.
     */
    public static final double TEACHER_WAGE_PER_DAY = 1.0;

    /**
     * 등교 하루당 <b>학교 주인에게 쌓이는 신세</b> — 수업료와 별개다.
     *
     * <p>왜 둘 다인가: 소액 수업료는 교육의 값을 다 치르지 못한다. 그 차액이 은혜로 남는 것이
     * 후원(patronage)의 실체다. 소작이 임금을 받으면서도 신세를 쌓는 것
     * ({@link AllegianceStore#W_TENANCY})과 같은 구조이고, 그 선례가 이미 이 코드에 있다.
     *
     * <p>1.0 은 감쇠 0.95 의 균형점이 20 이라, 100타일 지주의 추종 임계(20)를 <b>겨우</b> 넘는
     * 눈금이다. 큰 영주(200타일 → 임계 40)는 안 묶이고 중소 지주만 묶인다 — 이것이
     * <b>사슬을 붙잡는 못</b>이다(P4·P5a 실측: 지주 간 신세를 채워줄 경로가 없어 지배 계층이
     * 생겼다 사라졌다 했다).
     */
    public static final double W_SCHOOLING = 1.0;

    /**
     * 통학 한계(블록) — 밭 통근({@code FarmTicker.COMMUTE})과 <b>같은 48</b>.
     *
     * <p>같은 눈금을 쓰는 이유: 소년의 이동속도를 0.8 로 올린 것이 "통근으로 하루가 끝나면
     * 안 된다"(계획서 1.8)는 이유에서였고, 성년의 통근 한계가 이미 그 기준으로 잡혀 있다.
     * 학교만 다른 수를 쓰면 어느 쪽이 옳은지 판단할 근거가 둘로 갈린다.
     */
    public static final double COMMUTE_RANGE = 48.0;
}
